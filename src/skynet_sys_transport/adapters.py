from typing import Protocol
from skynet_sys.messages import Message
from .contracts import Delivery,Subscription,Inspection
class TransportAdapter(Protocol):
    """Future I/O must invoke this validated boundary; no callbacks or I/O here."""
    def publish(self,actor:str,topic:str,message:Message,tick:int)->tuple[Delivery,...]:...
    def subscribe(self,actor:str,topic:str,subscription_id:str,tick:int)->Subscription:...
    def unsubscribe(self,actor:str,subscription_id:str,tick:int)->Subscription:...
    def poll(self,actor:str,subscription_id:str,tick:int)->Delivery|None:...
    def ack(self,actor:str,delivery_id:str,attempt_number:int,tick:int)->Delivery:...
    def nack(self,actor:str,delivery_id:str,attempt_number:int,reason:str,tick:int)->Delivery:...
    def inspect(self,actor:str,tick:int)->Inspection:...
    def close(self,actor:str,tick:int)->bool:...
    def replay(self,actor:str,records:tuple)->'TransportAdapter':...
